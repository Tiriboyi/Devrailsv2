import path from 'node:path';
import {
  findRoot, exists, read, write, template, today, run, insertAfterMarker, replaceBetween, gitUser, log, c, CLI,
} from '../util.js';
import { loadConfig, getActiveRfcId } from '../config.js';
import { getRfc, getChangeRecord, acCoverage, tickCriteria, appendHistory, isSetupKey, resolveRfcKey, CR_DIR, ANALYSIS_DIR } from '../docs.js';
import { setFields } from '../frontmatter.js';
import { changedFiles, detectBase, classify } from '../gate.js';

const GEN_START = '<!-- devrailsv2:generated:start -->';
const GEN_END = '<!-- devrailsv2:generated:end -->';

function findAnalysis(root, ticket) {
  const m = String(ticket || '').match(/^(GH|ADO)#(\d+)/i);
  if (!m) return null;
  const rel = `${ANALYSIS_DIR}/TICKET-${m[1].toLowerCase()}-${m[2]}.md`;
  return exists(path.join(root, rel)) ? rel : null;
}

function runTests(root, cmd) {
  log.step(`Running tests: ${cmd}`);
  const r = run(cmd, [], { cwd: root, shell: true });
  const out = `${r.stdout}\n${r.stderr}`.trim().split(/\r?\n/);
  return { ok: r.ok, code: r.code, tail: out.slice(-40).join('\n') };
}

export default async function done({ flags }) {
  const root = findRoot();
  const cfg = loadConfig(root);
  const id = flags.rfc && flags.rfc !== true ? resolveRfcKey(root, flags.rfc) : getActiveRfcId(root);
  if (!id) throw new Error('No active RFC. Use --rfc <id>.');
  if (isSetupKey(id)) throw new Error(`RFC-${id} is the setup RFC; start a real RFC first.`);
  const rfc = getRfc(root, id);
  if (!rfc) throw new Error(`RFC-${id} not found.`);
  if (rfc.status !== 'approved') throw new Error(`RFC-${id} is "${rfc.status}", not approved.`);

  const base = flags.base && flags.base !== true ? flags.base : detectBase(root);
  const files = changedFiles(root, base).filter((f) => !f.startsWith(`${CR_DIR}/CR-${id}`));
  const tests = flags['run-tests'] ? runTests(root, cfg.testCommand) : null;
  const cov = acCoverage(root, cfg, id);
  const spec = cov.spec;
  const analysis = findAnalysis(root, rfc.ticket);

  // ---- generated section of the change record ----
  const byCat = {};
  for (const f of files) (byCat[classify(cfg, f)] ??= []).push(f);
  const catNames = { src: 'Source', legacy: 'Legacy system', test: 'Tests', other: 'Config / dependencies', docs: 'Docs', tooling: 'Tooling', free: 'RFC / spec / analysis' };
  const fileList = Object.entries(byCat)
    .map(([k, list]) => `**${catNames[k] || k}**\n${list.map((f) => `- \`${f}\``).join('\n')}`)
    .join('\n\n') || '_No changed files detected._';
  const acTable = cov.rows.length
    ? ['| Criterion | Tests referencing it |', '|---|---|', ...cov.rows.map((r) => `| RFC-${id}:${r.ac} ${r.text ? `— ${r.text.replace(/\|/g, '\\|')}` : ''} | ${r.tests.map((t) => `\`${t}\``).join(', ') || '**none**'} |`)].join('\n')
    : '_The RFC has no numbered acceptance criteria._';
  const testBlock = tests
    ? `${tests.ok ? '✅ passed' : `❌ failed (exit ${tests.code})`} — \`${cfg.testCommand}\` on ${today()}\n\n\`\`\`text\n${tests.tail}\n\`\`\``
    : `_Not run by devrailsv2. Use \`${CLI} done --run-tests\`._`;
  const generated = [
    '## Generated by devrailsv2',
    `_Regenerated each time \`devrailsv2 done\` runs. Base: ${base || 'none'}._`,
    '',
    '### Files changed',
    fileList,
    '',
    '### Acceptance-criteria coverage',
    acTable,
    '',
    '### Test run',
    testBlock,
  ].join('\n');

  // ---- change record ----
  const existing = getChangeRecord(root, id);
  const crRel = existing ? existing.relPath : `${CR_DIR}/CR-${id}-${rfc.slug}.md`;
  const crAbs = path.join(root, crRel);
  let cr = existing
    ? read(crAbs)
    : template('docs/change-record.md', {
        key: id,
        title: rfc.title,
        rfcFile: rfc.file,
        specLink: spec ? `[SPEC-${id}](../specs/${spec.file})` : 'none',
        ticket: rfc.ticket || 'none',
        analysis: analysis ? `[analysis](../../${analysis})` : 'none',
        date: today(),
      });
  cr = replaceBetween(cr, GEN_START, GEN_END, generated);
  write(crAbs, cr);
  log.ok(`${existing ? 'Updated' : 'Created'} ${crRel}`);

  // ---- CHANGELOG ----
  const clPath = path.join(root, 'CHANGELOG.md');
  const cl = exists(clPath) ? read(clPath) : template('docs/CHANGELOG.md');
  if (!cl.includes(`RFC-${id}`)) {
    write(clPath, insertAfterMarker(cl, '<!-- devrailsv2:unreleased -->', `- RFC-${id}: ${rfc.title} ([CR-${id}](${crRel}))`));
    log.ok('Added CHANGELOG.md entry');
  }

  // ---- STATUS ----
  const stPath = path.join(root, 'docs/STATUS.md');
  if (exists(stPath)) {
    const st = read(stPath);
    if (!st.includes(`CR-${id}`)) {
      write(stPath, insertAfterMarker(st, '<!-- devrailsv2:history -->', `- ${today()} — RFC-${id} ${rfc.title} implemented ([CR-${id}](changes/${path.basename(crRel)}))`));
      log.ok('Added docs/STATUS.md history entry');
    }
  }

  // ---- RFC: tick verified criteria, record implementation ----
  let rtext = read(rfc.absPath);
  const before = rtext;
  if (tests?.ok) {
    const verified = cov.rows.filter((r) => r.tests.length && !r.checked).map((r) => r.ac);
    if (verified.length) {
      rtext = tickCriteria(rtext, verified);
      log.ok(`Ticked ${verified.join(', ')} in the RFC (tests reference them and the suite passed)`);
    }
  } else if (cov.rows.some((r) => !r.checked)) log.info('Acceptance criteria are ticked only after `done --run-tests` passes.');
  if (!rtext.includes(`CR-${id}`)) {
    const u = gitUser(root);
    rtext = appendHistory(rtext, today(), u.name || u.email || 'devrailsv2', `Implemented — see CR-${id}`);
  }
  if (rtext !== before) write(rfc.absPath, setFields(rtext, { updated: today() }));

  if (cov.missing.length) log.warn(`Acceptance criteria without tests: ${cov.missing.join(', ')}`);
  if (tests && !tests.ok) log.err('Tests failed — the work is not done.');
  console.log(`
${c.bold('Now complete by hand (or have the agent do it):')}
  • ${crRel}: Summary, Fit-criteria evidence, Known limitations
  • docs/STATUS.md: "Where we are" and "Next step"
Then run: ${CLI} check`);
  return tests && !tests.ok ? 1 : 0;
}

